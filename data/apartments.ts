/**
 * Полосы жилых этажей на фасаде. Сняты с рендера по схеме сегментов от
 * архитекторов: шаг этажа 51.8 px (3.2 м), низ 1-го этажа на 1066 px,
 * ступени фасада совпадают с верхом 3-го, 7-го и 11-го. Ширина по сегментам:
 * 1–3 уже, 4–11 шире, 12–15 выходят над перемычкой к блоку B.
 */
export interface FacadeBand { floor: number; level: string; x: number; y: number; w: number; h: number; }

export const facadeImage = withVersion("/images/plans/facade.webp");

const FACADE = { W: 1086, H: 1449, step: 51.8, bottom: 1066, left: 157 };
const facadeRight = (floor: number) => (floor <= 3 ? 445 : floor <= 11 ? 482 : 612);

/** Сверху вниз — в том же порядке, что этажи на фасаде. */
export const facadeBands: FacadeBand[] = Array.from({ length: 15 }, (_, i) => {
  const floor = 15 - i;
  const top = FACADE.bottom - floor * FACADE.step;
  return {
    floor,
    level: `+${(4.8 + 3.2 * (floor - 1)).toFixed(2)}`,
    x: FACADE.left / FACADE.W,
    y: top / FACADE.H,
    w: (facadeRight(floor) - FACADE.left) / FACADE.W,
    h: FACADE.step / FACADE.H,
  };
});
