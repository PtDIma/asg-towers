/**
 * Квартиры блока A (левая башня), жилые этажи 1–15.
 *
 * Планировки повторяются сегментами: 1–3, 4–7, 8–11, 12–15. Каждый сегмент —
 * один типовой этаж из чертежа архитекторов (A Block Standard Floor Plans),
 * поэтому квартиры задаются здесь один раз на сегмент и размножаются по его
 * этажам.
 *
 * Номер квартиры: этаж + двузначный номер на этаже — 101, 1205, 1514.
 * Две цифры нужны, потому что на 12–15 по 14 квартир. По этому номеру
 * связаны Google Sheets (лист «Блок А») и карточка квартиры.
 *
 * Контуры получены не по растру этажа, а переносом: поквартирный чертёж
 * (Plan/A_<сегмент>_<n>.png) — вырезка того же CAD, на нём нарисована только
 * эта квартира. Его нашли на плане этажа шаблонным поиском (корреляция
 * 0.78–0.98) и перенесли силуэт. Проверка — площадь силуэта к площади из
 * чертежа: у всех 42 типов в пределах ±7%.
 *
 * Площади — из красных подписей «საერთო ფართი» в чертеже, включают балкон.
 * Цены и статусы — из Google Sheets, здесь их нет.
 */

export interface ApartmentGeo {
  id: string;
  floor: number;
  /** Общая площадь, м². Включает балкон. */
  area: number;
  /** Ключ чертежа квартиры: A_<сегмент>_<номер на этаже>. По нему лежат 2D и 3D. */
  plan: string;
  /** Есть объёмная визуализация. Без неё карточка показывает только чертёж. */
  has3d: boolean;
  /** Точка подписи на плане этажа (доли изображения) — якорь для метки. */
  nx: number;
  ny: number;
  /** Контуры помещений на плане этажа, доли изображения. */
  poly: [number, number][][];
}

export interface FloorPlan { floor: number; image: string; width: number; height: number; units: ApartmentGeo[]; }

