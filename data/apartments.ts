export const floorPlans: FloorPlan[] = segments.flatMap((s) =>
  Array.from({ length: s.to - s.from + 1 }, (_, i) => {
    const floor = s.from + i;
    return {
      floor,
      image: withVersion(`/images/plans/floor-${s.key}.webp`),
      width: s.width,
      height: s.height,
      units: s.types.map((t) => {
        const plan = `A_${s.key}_${t.n}`;
        return {
          id: `${floor}${String(t.n).padStart(2, "0")}`,
          floor,
          area: t.area,
          plan,
          has3d: PLANS_3D.has(plan),
          nx: t.nx,
          ny: t.ny,
          poly: [t.poly],
        };
      }),
    };
  })
);

